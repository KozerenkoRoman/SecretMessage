func EncodeName(name string) string {
	c32 := crc32.ChecksumIEEE([]byte(name))
	idx := int(math.Abs(float64(int32(c32))))

	adj := ADJECTIVES[(idx+13412)%len(ADJECTIVES)]
	noun := NOUNS[(idx*139)%len(NOUNS)]

	return fmt.Sprintf("%s-%s",
		strings.ToUpper(adj[:1])+adj[1:],
		strings.ToUpper(noun[:1])+noun[1:],
	)
}
